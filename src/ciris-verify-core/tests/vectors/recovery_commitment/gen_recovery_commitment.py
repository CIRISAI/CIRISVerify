# Independent known answers for the recovery commitment (CC 3.2 T3, CC 4.2.6, rc20):
#
#   commitment = [-16, SHA-256( CDE( ["CEG-recovery/2", keys] ) )]
#
# `keys` is a set of ceg-key {1: 7, 3: -70100, -1: <1984-byte composite pub>}, sorted by the bytewise order of
# each element's deterministic encoding, with no duplicate (CC 2.6.1.2). A per-holder commitment has one key.
# The keys are the composite keys of the accord-halt known-answer roster (../accord_halt): ML-DSA-65 xi and
# Ed25519 seed 0xa1/0x1a (A1), 0xb1/0x1b (B1), 0xc1/0x1c (C1), each x 32. Shares no code with verify:
# dilithium-py, pyca/cryptography and the CBOR encoder below.
#
#   python3 -I gen_recovery_commitment.py > recovery_commitment_v1.json
import hashlib, json, sys
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization as ser
from dilithium_py.ml_dsa import ML_DSA_65


def head(major, n):
    if n < 24: return bytes([major << 5 | n])
    for ai, w in ((24, 1), (25, 2), (26, 4), (27, 8)):
        if n < 1 << (8 * w): return bytes([major << 5 | ai]) + n.to_bytes(w, "big")
def enc(v):
    if isinstance(v, int): return head(0, v) if v >= 0 else head(1, -1 - v)
    if isinstance(v, bytes): return head(2, len(v)) + v
    if isinstance(v, str): return head(3, len(v.encode())) + v.encode()
    if isinstance(v, list): return head(4, len(v)) + b"".join(enc(x) for x in v)
    if isinstance(v, dict):
        items = sorted((enc(k), enc(x)) for k, x in v.items())
        return head(5, len(items)) + b"".join(k + x for k, x in items)
    raise TypeError(v)


def composite_pub(ml_seed, ed_seed):
    ml_pk, _ = ML_DSA_65.key_derive(bytes([ml_seed]) * 32)
    ed = Ed25519PrivateKey.from_private_bytes(bytes([ed_seed]) * 32).public_key()
    return ml_pk + ed.public_bytes(ser.Encoding.Raw, ser.PublicFormat.Raw)


KEYS = {l: composite_pub(m, e) for l, m, e in (("A1", 0xa1, 0x1a), ("B1", 0xb1, 0x1b), ("C1", 0xc1, 0x1c))}
ceg_key = lambda pub: {1: 7, 3: -70100, -1: pub}
sorted_labels = sorted(KEYS, key=lambda l: enc(ceg_key(KEYS[l])))


def commitment(labels):
    # The set: sorted by encoding, one of each.
    keys = sorted({enc(ceg_key(KEYS[l])): ceg_key(KEYS[l]) for l in labels}.items())
    preimage = enc(["CEG-recovery/2", [k for _, k in keys]])
    digest = hashlib.sha256(preimage).digest()
    return preimage, digest


unsorted = list(reversed(sorted_labels))
other = [sorted_labels[1], sorted_labels[2], sorted_labels[0]]
assert unsorted != sorted_labels and other != sorted_labels and other != unsorted
cases = []
for cid, desc, labels in [
    ("one_key", "A1's per-holder recovery commitment: one key (CC 4.2.6).", ["A1"]),
    ("one_key_b1", "B1's per-holder recovery commitment.", ["B1"]),
    ("one_key_c1", "C1's per-holder recovery commitment.", ["C1"]),
    ("three_keys_unsorted", "A1, B1 and C1 given in descending encoding order; the set sorts them.", unsorted),
    ("three_keys_other_order", "The same three in a third order: the same set, so the same digest.", other),
    ("duplicate_key", "A1 given twice: the set holds it once, so the digest is one_key's.", ["A1", "A1"]),
]:
    pre, dig = commitment(labels)
    cases.append({"id": cid, "description": desc, "input_keys": labels,
                  "input_composite_public_keys_hex": [KEYS[l].hex() for l in labels],
                  "set_order": sorted(set(labels), key=lambda l: enc(ceg_key(KEYS[l]))),
                  "cde_hex": pre.hex(), "digest_hex": dig.hex(),
                  "commitment_cde_hex": enc([-16, dig]).hex()})

by = {c["id"]: c for c in cases}
assert by["three_keys_unsorted"]["digest_hex"] == by["three_keys_other_order"]["digest_hex"]
assert by["duplicate_key"]["digest_hex"] == by["one_key"]["digest_hex"]
assert by["duplicate_key"]["cde_hex"] == by["one_key"]["cde_hex"]

json.dump({"$note": ("Recovery commitments (CC 3.2 T3, CC 4.2.6, rc20): digest = SHA-256(CDE(['CEG-recovery/2', keys])), "
                     "carried as [-16, digest] (commitment_cde_hex). keys is a set of ceg-key {1: 7, 3: -70100, -1: pub}, "
                     "sorted by the bytewise order of each key's deterministic encoding, no duplicate. Keys are the "
                     "accord-halt KAT roster (seeds a1/1a, b1/1b, c1/1c). Generated by gen_recovery_commitment.py with "
                     "dilithium-py and pyca/cryptography, independent of verify."),
           "keys": {l: {"composite_public_key_hex": p.hex(), "ceg_key_cde_sha256": hashlib.sha256(enc(ceg_key(p))).hexdigest()}
                    for l, p in KEYS.items()},
           "set_order": sorted_labels, "cases": cases}, sys.stdout, indent=1, sort_keys=True)
print()
